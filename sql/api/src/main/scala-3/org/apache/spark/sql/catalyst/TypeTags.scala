package org.apache.spark.sql.catalyst

/**
 * The type tags that Spark SQL APIs such as `Encoders.product` and `functions.udf` take.
 *
 * Scala 3 has no `scala.reflect.runtime.universe.TypeTag`, so the Scala 3 build defines its own
 * `TypeTag`. The compiler materializes one for any statically known type, and the tag describes
 * the type to [[ScalaReflection]] with the facts the Scala 2.13 build reads through Scala
 * reflection.
 */
object TypeTags {

  /** Describes the static type `T`. Use it as a context bound, as with the Scala 2 type tag. */
  trait TypeTag[T] extends Serializable {
    /** The description of `T`. This is internal to Spark SQL. */
    def desc: TypeDesc

    /** The same as [[desc]]. Named after the member of the Scala 2 type tag. */
    def tpe: TypeDesc = desc

    override def toString: String = s"TypeTag[${desc.typeName}]"
  }

  object TypeTag {
    inline given materialize[T]: TypeTag[T] = ${ TypeTagMacros.materialize[T] }

    /**
     * Builds a tag from the entries that [[TypeTagMacros]] generates. Entry 0 describes `T`. Each
     * entry is a [[TypeSpec]], or the [[TypeTag]] of an abstract type that the call site has.
     * Specs refer to other entries by index, which lets recursive types refer to themselves.
     */
    def fromEntries[T](entries: Seq[Any]): TypeTag[T] = {
      val table = new Array[TypeDesc](entries.length)
      entries.zipWithIndex.foreach {
        case (spec: TypeSpec, i) => table(i) = new TypeDesc(spec, table)
        case (tag: TypeTag[_], i) => table(i) = tag.desc
        case (other, _) => throw new IllegalArgumentException(s"Unexpected type entry $other")
      }
      new DescribedTypeTag[T](table(0))
    }
  }

  private final class DescribedTypeTag[T](override val desc: TypeDesc) extends TypeTag[T]

  /** Returns the type tag of `T`, as `scala.reflect.runtime.universe.typeTag` does in Scala 2. */
  def typeTag[T](implicit ttag: TypeTag[T]): TypeTag[T] = ttag
}

/**
 * What the compiler knows about one type, as generated by [[TypeTagMacros]]. `args` and
 * `fieldTypes` are indices of entries of the same tag. `cls` is null for an array whose element
 * type is abstract. `typeName` is the type as Scala 2 prints it, for error messages.
 * `constructorError` is [[TypeSpec.NoConstructor]] or [[TypeSpec.NoPrimaryConstructor]] if a
 * product type has no usable constructor, and 0 otherwise.
 */
final class TypeSpec(
    val cls: Class[_],
    val typeName: String,
    val className: String,
    val kind: Int,
    val args: Seq[Int],
    val hasNewBuilder: Boolean,
    val enumParent: Class[_],
    val fieldNames: Seq[String],
    val fieldTypes: Seq[Int],
    val constructorError: Int) extends Serializable

object TypeSpec {
  val Regular = 0
  val NullType = 1
  val NothingType = 2

  val NoConstructor = 1
  val NoPrimaryConstructor = 2
}

/** A type described by a [[TypeSpec]], with its type arguments and fields resolved. */
final class TypeDesc private[catalyst] (spec: TypeSpec, table: Array[TypeDesc])
  extends Serializable {

  lazy val typeArgs: Seq[TypeDesc] = spec.args.map(table(_))

  lazy val runtimeClass: Class[_] = if (spec.cls != null) {
    spec.cls
  } else {
    java.lang.reflect.Array.newInstance(typeArgs.head.runtimeClass, 0).getClass
  }

  def typeName: String = spec.typeName

  def className: String = spec.className

  def isNull: Boolean = spec.kind == TypeSpec.NullType

  def isNothing: Boolean = spec.kind == TypeSpec.NothingType

  def hasNewBuilder: Boolean = spec.hasNewBuilder

  def enumParent: Class[_] = spec.enumParent

  def constructorError: Int = spec.constructorError

  lazy val fields: Seq[(String, TypeDesc)] = spec.fieldNames.zip(spec.fieldTypes.map(table(_)))

  override def toString: String = typeName
}
